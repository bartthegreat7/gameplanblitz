import { screen, within } from '@testing-library/react'

import { mockFetch, PLAYERS, renderApp, resetStore } from './test/mockSleeper'

/* My starters rb1 + wr1; wr1 is Questionable. Free agent fa1 (12 proj) beats rb1 (8). */
const SLOW = { timeout: 15_000 }

beforeEach(() => {
  resetStore({ username: 'me' })
  mockFetch({
    '/players/nfl': { ...PLAYERS, wr1: { ...PLAYERS.wr1, injury_status: 'Questionable' } },
  })
})
afterEach(() => vi.unstubAllGlobals())

describe('The Edge', () => {
  it('ranks every decision by urgency with data, effect, uncertainty, deadline and sources', async () => {
    renderApp('#/edge')
    const week = await screen.findByRole('region', { name: 'This week' }, SLOW)
    const watch = await within(week).findByRole(
      'listitem',
      { name: 'Monitor W. Catchwell (Questionable)' },
      SLOW,
    )
    expect(watch).toHaveTextContent('Questionable: a game-time decision.')
    expect(watch).toHaveTextContent(/Expected effect\s*10\.0 projected pts at stake/)
    expect(watch).toHaveTextContent(/Uncertainty\s*The designation can change before kickoff/)
    expect(watch).toHaveTextContent(
      /Deadline\s*Before kickoff on Sun, Nov 2 \(kickoff time not published\)/,
    )
    expect(watch).toHaveTextContent(
      /Data sources\s*Sleeper injury designation · Sleeper projections/,
    )
    expect(within(watch).getByRole('link', { name: /Open Injury Center/ })).toHaveAttribute(
      'href',
      '#/injuries',
    )
    const add = await within(week).findByRole('listitem', { name: /Add F\. Agentson/ }, SLOW)
    expect(add).toHaveTextContent(/Expected effect\s*\+4\.0 pts\/wk/)
    expect(screen.getByText(/nothing here is generated by AI/)).toBeInTheDocument()
  })

  it('shows the weekly report on the Fantasy GM page', async () => {
    renderApp('#/gm')
    const injuries = await screen.findByRole('region', { name: 'Injury concerns' }, SLOW)
    expect(within(injuries).getByText('Wideout Catchwell')).toBeInTheDocument()
    expect(within(injuries).getAllByText('Questionable')).toHaveLength(2) // wr1 here, rb2 in the base mock
    const lineup = screen.getByRole('region', { name: 'Recommended lineup' })
    expect(lineup).toHaveTextContent('R. Runnerson')
    expect(
      await within(screen.getByRole('region', { name: 'Waiver opportunities' })).findByText(
        /F\. Agentson/,
        {},
        SLOW,
      ),
    ).toBeInTheDocument()
    expect(screen.getByRole('region', { name: 'Weather risks' })).toHaveTextContent(
      'No flagged forecasts',
    )
    expect(
      within(screen.getByRole('main')).getByRole('link', { name: 'The Edge' }),
    ).toHaveAttribute('href', '#/edge')
  })
})

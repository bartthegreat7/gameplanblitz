import { ArrowRight, Zap } from 'lucide-react'
import { Link } from 'react-router-dom'

import { ProjNotice } from '../components/cards/shared'
import { LeagueGate } from '../components/LeagueGate'
import { ConfidenceBadge } from '../components/ui/badges'
import { EmptyState, ListSkeleton, Notice } from '../components/ui/states'
import { useGmBrief } from '../hooks/useGmBrief'
import type { Ready } from '../hooks/useLeagueData'
import type { Area, GmAction, Priority } from '../lib/analytics/gm'

const GROUP: Record<Priority, { title: string; sub: string }> = {
  1: {
    title: 'Do now',
    sub: 'A fact in your lineup needs fixing, or a starter is unlikely to play.',
  },
  2: { title: 'This week', sub: 'Projected upgrades, injury watches and news about your players.' },
  3: {
    title: 'Worth considering',
    sub: 'Waiver investigations, weather to review, trades and longer-term moves.',
  },
}

const TOOL: Record<Area, string> = {
  lineup: 'Lineup Optimizer',
  injury: 'Injury Center',
  weather: 'Lineup Optimizer',
  waivers: 'Waiver Sniper',
  breakout: 'the evidence',
  trades: 'Trade War Room',
  news: 'News & Articles',
  playoffs: 'Playoff Simulator',
  keepers: 'Keeper Intelligence',
}

function Field({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div className="grid gap-0.5 sm:grid-cols-[9rem_1fr] sm:gap-3">
      <dt className="text-ink-3">{label}</dt>
      <dd className="text-ink-2">{children}</dd>
    </div>
  )
}

function ActionCard({ a, n }: { a: GmAction; n: number }) {
  return (
    <li aria-label={a.title} className="border-line bg-card rounded-2xl border p-5">
      <div className="flex flex-wrap items-start gap-3">
        <span className="bg-accent/12 text-accent grid size-8 shrink-0 place-items-center rounded-full text-sm font-extrabold">
          {n}
        </span>
        <h3 className="min-w-0 flex-1 text-lg leading-snug font-extrabold">{a.title}</h3>
        {a.confidence && <ConfidenceBadge confidence={a.confidence} />}
      </div>
      <dl className="mt-3 grid gap-2 text-sm">
        {a.detail && <Field label="Supporting data">{a.detail}</Field>}
        <Field label="Expected effect">
          <b className="text-ink">{a.impact}</b>
        </Field>
        <Field label="Uncertainty">
          {a.uncertainty ??
            (a.confidence
              ? `${a.confidence.level} confidence: ${a.confidence.notes.join('; ')}`
              : 'Not rated')}
        </Field>
        {a.deadline && <Field label="Deadline">{a.deadline}</Field>}
        <Field label="Data sources">{a.sources.join(' · ')}</Field>
      </dl>
      <Link
        to={a.to}
        className="text-accent mt-3 inline-flex items-center gap-1 text-sm font-bold hover:underline"
      >
        Open {TOOL[a.area]} <ArrowRight size={14} aria-hidden />
      </Link>
    </li>
  )
}

function EdgeView({ data }: { data: Ready }) {
  const { allActions, pending, unavailable } = useGmBrief(data)
  let n = 0
  return (
    <div className="mx-auto max-w-4xl">
      <h1 className="flex items-center gap-2 text-2xl font-extrabold tracking-tight md:text-3xl">
        <Zap size={24} aria-hidden className="text-accent" /> The Edge
      </h1>
      <p className="text-ink-2 mt-1">
        Every decision worth your attention this week, ranked by urgency: your lineup, injury
        watches, waiver and breakout investigations, weather, trades, the playoff race and keepers.
        Each item shows the data behind it, its expected effect, what could make it wrong, the
        deadline and the sources. Rules-based from the app&apos;s own calculations; nothing here is
        generated by AI.
      </p>
      <ProjNotice data={data} />
      {pending.length > 0 && (
        <Notice tone="ok">Still checking: {pending.join(', ')}. More items may appear.</Notice>
      )}
      {unavailable.length > 0 && <Notice>Not included this time: {unavailable.join('; ')}.</Notice>}
      {allActions.length === 0 ? (
        pending.length > 0 ? (
          <ListSkeleton rows={4} />
        ) : (
          <div className="mt-5">
            <EmptyState>Nothing needs your attention this week.</EmptyState>
          </div>
        )
      ) : (
        ([1, 2, 3] as Priority[]).map((p) => {
          const items = allActions.filter((a) => a.priority === p)
          if (items.length === 0) return null
          return (
            <section key={p} aria-label={GROUP[p].title} className="mt-6">
              <h2 className="text-xl font-extrabold tracking-tight">
                {GROUP[p].title}{' '}
                <span className="text-ink-3 text-base font-bold">({items.length})</span>
              </h2>
              <p className="text-ink-3 mb-3 text-sm">{GROUP[p].sub}</p>
              <ol className="grid gap-3">
                {items.map((a) => (
                  <ActionCard key={a.id} a={a} n={++n} />
                ))}
              </ol>
            </section>
          )
        })
      )}
      <details className="border-line bg-card mt-6 rounded-2xl border p-5 text-sm">
        <summary className="cursor-pointer font-bold">How this list is built</summary>
        <ul className="text-ink-2 mt-3 grid list-disc gap-1 pl-5">
          <li>Do now: empty, bye or Out starters (Sleeper facts) and Doubtful starters.</li>
          <li>
            This week: lineup changes worth 0.5+ projected points, Questionable starters (with your
            best eligible backup), roster news from the last 72 hours, the best waiver upgrade.
          </li>
          <li>
            Worth considering: free agents with rising usage or more work when an injured teammate
            sat, starters whose forecast is flagged (context only), the best trade both teams gain
            from, the playoff race while it is open, keeper savings.
          </li>
          <li>
            Within each group, the order is by kind (lineup first), then by size of the effect.
          </li>
        </ul>
      </details>
    </div>
  )
}

export default function Edge() {
  return <LeagueGate>{(data) => <EdgeView data={data} />}</LeagueGate>
}
